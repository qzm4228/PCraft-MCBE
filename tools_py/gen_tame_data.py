"""Generate behavior_pack/scripts/pcraftrevorn/data/tame.js from the entities.

The entities are the source of truth: minecraft:tameable gives the right-click
bribe (items + probability); every creature with a pcraftrevorn:on_tame event can
also be tamed by the cupid's arrow projectile (game/cupid.js). Runs in the
pipeline after generate_entities so the guide can never drift from the engine.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENT = ROOT / "behavior_pack/entities"
OUT = ROOT / "behavior_pack/scripts/pcraftrevorn/data/tame.js"

rows = []
for p in sorted(ENT.glob("*.json")):
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except Exception:
        continue
    ent = data.get("minecraft:entity", {})
    if not ent:
        continue
    ident = (ent.get("description", {}) or {}).get("identifier") or ""
    comp = (ent.get("components", {}) or {}).get("minecraft:tameable")
    has_event = "pcraftrevorn:on_tame" in ((ent.get("events", {}) or {}))
    if not comp and not has_event:
        continue
    key = ident.split(":", 1)[-1]
    items = (comp or {}).get("tame_items") or []
    if isinstance(items, str):
        items = [items]
    chance = (comp or {}).get("probability", (comp or {}).get("tame_chance", 1))
    rows.append((key, items, float(chance)))

rows.sort()

lines = [
    "// Taming table -- generated by tools_py/gen_tame_data.py from the entities.",
    "//   items : right-click bribe (empty = cupid's arrow projectile only)",
    "//   chance: success chance for that item",
    "// Every entry can also be tamed by the cupid's arrow (game/cupid.js).",
    "export const TAME = {",
]
for key, items, chance in rows:
    item_list = ", ".join(f'"{i}"' for i in items)
    lines.append(f'  "{key}": {{ items: [{item_list}], chance: {chance:g} }},')
lines.append("};")
lines.append("")

OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"[tame] wrote {OUT.relative_to(ROOT)}: {len(rows)} tameable creatures")
